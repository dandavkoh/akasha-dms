using Akasha.Domain.Documents;
using Akasha.Domain.Storage;

namespace Akasha.Application.Documents;

public sealed record StorageReferenceView(
    Guid ConnectorId,
    string ExternalId,
    string Path,
    string Name,
    string? Version,
    string? ETag,
    DateTimeOffset? LastKnownModifiedAtUtc,
    StorageSyncState SyncState);

public sealed record DocumentView(
    Guid Id,
    string Name,
    StorageSyncState State,
    ProcessingState Processing,
    StorageReferenceView Storage,
    /// <summary>Optimistic concurrency token (PostgreSQL xmin); required for updates.</summary>
    uint RowVersion,
    DateTimeOffset CreatedAtUtc,
    DateTimeOffset UpdatedAtUtc);

public sealed record PagedResult<T>(IReadOnlyList<T> Items, int Total, int Skip, int Take);

/// <summary>
/// Registers a logical document for a file that already exists in a connected storage.
/// The DocumentId is generated by Akasha and never derived from any of these values.
/// </summary>
public sealed record CreateDocumentRequest(
    Guid ConnectorId,
    string ExternalId,
    string Path,
    string Name,
    string? Version = null,
    string? ETag = null,
    DateTimeOffset? LastKnownModifiedAtUtc = null);

public sealed record RenameDocumentRequest(string Name, uint RowVersion);

/// <summary>
/// Application service for logical documents. Every operation establishes tenant context,
/// authorizes via <c>IAuthorizationService</c> before touching data, uses PostgreSQL xmin
/// optimistic concurrency for updates and writes audit entries for mutations.
///
/// Content operations (upload/download/physical move or delete) go through the storage
/// connector abstraction and are added once the connector registry exists.
/// </summary>
public interface IDocumentService
{
    Task<PagedResult<DocumentView>> ListAsync(int skip, int take, CancellationToken cancellationToken = default);

    Task<DocumentView> GetAsync(Guid id, CancellationToken cancellationToken = default);

    Task<DocumentView> CreateAsync(CreateDocumentRequest request, CancellationToken cancellationToken = default);

    Task<DocumentView> RenameAsync(Guid id, RenameDocumentRequest request, CancellationToken cancellationToken = default);

    /// <summary>Logical deletion only; the physical customer file is never touched here.</summary>
    Task DeleteAsync(Guid id, CancellationToken cancellationToken = default);
}
